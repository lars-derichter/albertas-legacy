// sprite-speler.js — de speler: Alberta's kleinkind op zolder. Geen naam, geen
// geslacht, geen gezicht — dat is de norm uit achtergrond.md (§De speler), en ze
// staat nu ook in de pixels: een kleine, alledaagse figuur in een trui en een
// jeans, kort haar, geen ogen en geen mond. Roodkapje leeft alleen nog in de
// sim-fictie; de rode mantel (palet 4/12) is hier weg.
//
// Vijftien breed, eenendertig hoog (de doorzwaaiframes tweeëndertig) — binnen de
// 16×32 van art-stijlgids.md, §Sprite-specificaties, en op de ± 1/6 schermhoogte
// die diezelfde gids vraagt.
//
// ---- Licht -----------------------------------------------------------------
//
// Het dakraam staat in elke kamer rechts; elke prop heeft zijn schaduw links.
// Deze frames zijn zo getekend: de donkerste trap van elke ramp staat links, de
// lichtste rechts. West is en blijft gespiegeld oost (engine.js, tekenActor), en
// dat keert de belichting mee om — een bewuste ruil. Alles wat je stilstaand
// ziet klopt met de kamer; alleen tijdens het naar links lópen zit het licht een
// paar tellen aan de verkeerde kant, en dat is de prijs voor de helft minder
// frames.
//
// Sub-palet-codering (sprite-schema.md, §Het sub-palet): de frame-tekens 0–d
// verwijzen naar 'palet' hieronder, dat lokale indexen op echte paletindexen
// afbeeldt. Zo put deze kleine sprite toch uit de volle 64 kleuren.
//   0 -> 0  zwart (zolen, contactrand)
//   1 -> 42 trui diepst (mouwnaad, zoom)
//   2 -> 43 trui schaduw (de linkerkant)
//   3 -> 44 trui mid
//   4 -> 45 trui licht (de dakraamkant, rechts)
//   5 -> 59 jeans diepst (binnenbeen)
//   6 -> 60 jeans schaduw
//   7 -> 61 jeans licht
//   8 -> 18 huid schaduw
//   9 -> 19 huid mid
//   a -> 20 huid hooglicht (rechterkant)
//   b -> 23 haar schaduw (kort, donkerbruin)
//   c -> 24 haar licht
//   d -> 49 schoen (koelgrijs)
//
// ---- Over de animatie ------------------------------------------------------
//
//   ademen      Elke sta-anim heeft twee frames op 1 Hz. Op de tweede zakt het
//               hoofd één pixel en wordt de romp één rij korter. Eén pixel is
//               genoeg: het is het verschil tussen een sprite en een standbeeld.
//
//   deining     De loopcycli hebben vier frames: twee steunfases (voeten uit
//               elkaar) en twee doorzwaaifases (voeten bij elkaar). De
//               doorzwaaiframes zijn tweeëndertig rijen hoog in plaats van
//               eenendertig. Omdat het ankerpunt onderaan-midden ligt, blijven de
//               voeten dus staan en gaat de rómp een pixel omhoog — precies wat
//               er gebeurt als je over je steunbeen heen rolt. Dat ene pixel doet
//               meer voor "dit is lopen" dan de voetstanden samen.
//
//   armzwaai    Alleen in het zijaanzicht, want alleen daar is er breedte voor.
//               De mouw komt vóór de romp uit en zwaait in vier fasen: vooruit,
//               half, weg (achter de romp, in de schaduwtrap), half. Van voren en
//               van achteren zitten de armen ín het silhouet; daar leest een naad
//               van één pixel meer dan een uitstekende arm.
//
//   draai       Eén frame, driekwart: de romp nog bijna van voren, het hoofd al
//               opzij. De engine zet die twee tikken lang neer als de speler van
//               de noord-zuidas naar de oost-westas wisselt. Zonder dat frame
//               klapt de figuur van de ene kant naar de andere.
//
//   zitten      Drie frames: staan, hurken, zitten. De engine speelt ze af vóór
//               de pc-overlay opengaat, want anders zie je nooit dat het kind
//               gaat zitten — het scherm neemt het beeld meteen over. Het anker
//               blijft onderaan-midden, dus wie korter wordt, zakt op zijn plek.
//
// De rijen zijn allemaal exact vijftien tekens lang; test/test-sprites.mjs zakt
// als er één afwijkt.
