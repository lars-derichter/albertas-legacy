// en loopframes, hertekend naar het sub-palet-formaat en de AL-namespace.
//
// ---- Over de animatie ------------------------------------------------------
//
// De figuur stond stil en liep met twee frames waarin alléén de voeten bewogen.
// Daardoor las lopen als schuifelen: een romp die met constante hoogte over de
// vloer glijdt terwijl er onderaan iets wisselt. Wat er nu bij is:
//
//   ademen      Elke sta-anim heeft twee frames op 1 Hz. Op de tweede zakt het
//               hoofd één pixel en wordt de mantel één rij korter. Eén pixel is
//               genoeg: op een figuur van vijfentwintig pixels hoog is dat vier
//               procent, en het verschil tussen een sprite en een standbeeld.
//
//   deining     De loopcycli hebben vier frames: twee steunfases (voeten uit
//               elkaar) en twee doorzwaaifases (voeten bij elkaar). De
//               doorzwaaiframes zijn zésentwintig rijen hoog in plaats van
//               vijfentwintig. Omdat het ankerpunt onderaan-midden ligt, staan de
//               voeten dus stil en gaat de rómp een pixel omhoog — precies wat er
//               gebeurt als je over je steunbeen heen rolt. Dat ene pixel doet
//               meer voor "dit is lopen" dan de voetstanden samen.
//
//   armzwaai    Alleen in het zijaanzicht, want alleen daar is er breedte voor.
//               Een mouw van twee pixels breed komt vóór de mantel uit en zwaait
//               in vier fasen: vooruit, half, weg, half. Van voren en van achteren
//               zitten de armen ín het silhouet; daar zou een arm een rode vlek
//               zijn en niets meer.
//
//   draai       Eén frame, driekwart. De engine zet die twee tikken lang neer als
//               de speler van de noord-zuidas naar de oost-westas wisselt. Zonder
//               dat frame klapt de figuur van de ene kant naar de andere.
//
//   zitten      Drie frames: staan, hurken, zitten. De engine speelt ze af vóór
//               de pc-overlay opengaat, want anders zie je nooit dat het kind
//               gaat zitten — het scherm neemt het beeld meteen over.
//
// Alle maten blijven binnen de 16×32 die de stijlgids toestaat (13 breed, 25 of
// 26 hoog). West blijft gespiegeld oost; er zit dus niets in deze frames dat
// gespiegeld fout oogt.
