// (`links`) en hoe breed ze is (`breedte`). De hand is proportioneel — dat is
// het halve punt van een handschrift — en de renderer schuift per teken op met
// inkt + spatiëring.
(function () {
  var glyphs = AL.fontHand.glyphs;
  var maten = {};
  for (var ch in glyphs) {
    if (!Object.prototype.hasOwnProperty.call(glyphs, ch)) continue;
    var rijen = glyphs[ch];
    var links = AL.fontHand.breedte, rechts = -1;
    for (var r = 0; r < rijen.length; r++) {
      for (var c = 0; c < AL.fontHand.breedte; c++) {
        if (rijen[r].charAt(c) !== "1") continue;
        if (c < links) links = c;
        if (c > rechts) rechts = c;
      }
    }
    maten[ch] = rechts < 0
      ? { links: 0, breedte: 0 }
      : { links: links, breedte: rechts - links + 1 };
  }

  // Het woordwit. Drie pixels tegen vier in de drukfont: de handletters zijn
  // smaller, dus een wit van vier zou de woorden uit elkaar trekken. Met de
  // spatiëring erbij staat er vier pixels tussen twee woorden en één tot twee
  // tussen twee letters — genoeg verschil om als woordwit te lezen.
  maten[" "] = { links: 0, breedte: 3 };

  AL.fontHand.maten = maten;
  AL.fontHand.spatiering = 1;

  AL.fontHand.maat = function (ch) {
    return maten[ch] || maten["?"] || { links: 0, breedte: AL.fontHand.breedte };
  };

  AL.fontHand.voortgang = function (ch) {
    return AL.fontHand.maat(ch).breedte + AL.fontHand.spatiering;
  };
})();

// Node-export voor de headless tests.
if (typeof module !== "undefined") {
  module.exports = AL.fontHand;
}
