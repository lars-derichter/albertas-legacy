// font-hand.js — Alberta's hand. Een tweede, écht getekende glyphset naast de
// gedrukte 8×8-BIOS-font in js/font.js, alleen voor het notitieboek-spread.
//
// Waarom een aparte font en niet nog een truc op de drukfont: tot WP 36 wérd
// het handschrift de drukfont, scheefgetrokken met een shear van 0,25 en op en
// neer geduwd met een driehoeksgolf met periode vier tekens. Die golf was
// index-gebaseerd, dus élke regel deinde identiek — wat op een blad met twaalf
// regels als verticale banding leest, niet als een hand. En een scheve
// bitmapletter blijft een bitmapletter: de vorm is nog altijd die van een
// terminal uit 1990. De onregelmatigheid zit nu in de glyphs zelf.
//
// De cel is 8 kolommen breed en 10 RIJEN hoog, tegen 8×8 voor de drukfont. Die
// twee extra rijen zijn de staartzone; ze passen binnen BLAD.regelH (11), dus
// de regelafstand van het notitieboek verandert niet.
//
//   rij 0–1   stokzone en accenten (b d f h k l t, é ë ï, hoofdletters)
//   rij 2–7   de x-hoogte: zes rijen, de romp van elke kleine letter
//   rij 7     de nominale basislijn — de onderste inktrij van een romp
//   rij 8     de rij waar de LINIATUUR van het sjabloon loopt
//   rij 9     de staartzone (g j p q y, komma)
//
// De liniatuur van scene-spread-template.js staat op y = topY + n·regelH + 8,
// dus precies op rij 8 van de cel. Een glyph zonder verschuiving zit met zijn
// basislijn (rij 7) tégen die lijn: Alberta schrijft óp de lijn.
//
// ONREGELMATIGE BASISLIJN, GEBAKKEN. Elke glyph heeft zijn eigen ligging, en
// die staat in de data, niet in een formule:
//
//   −1  a m r K V 7      de romp eindigt op rij 6: één pixel boven de lijn
//    0  het merendeel    de romp eindigt op rij 7: op de lijn
//   +1  c i n u z D G S 3   de romp eindigt op rij 8: op de lijn zelf
//
// Omdat de ligging aan het teken hangt en niet aan de positie in de regel, kan
// ze per definitie geen patroon vormen dat over de regels heen als banding
// leest: "een" deint anders dan "nee", en elke regel deint anders omdat er
// andere letters in staan.
//
// VARIABELE INKTBREEDTE. De maten worden onderaan berekend, net als in
// font.js: van de "i" (2 px) tot de "m" en de "w" (7 px). Gemiddeld valt de
// hand ongeveer een pixel per teken smaller uit dan de drukfont — precies wat
// het bladbudget van test/test-spreads.mjs kan gebruiken.
//
// SCHUINSTAND, GEBAKKEN. De stokken van b d f h k l t staan bovenaan één kolom
// rechts van hun voet, de staarten van g j p q y buigen naar links. Dat is een
// echte helling van de pen; de oude shear kantelde het hele raster en zette
// daarbij ook punten en streepjes scheef. gfx.tekenHandschrift kent nog een
// `schuin`-optie, maar ze staat voor deze font op 0.
//
// Dekking: alles wat js/font.js dekt (drukbare ASCII 32–126, de accenten die
// het Vlaams nodig heeft, de em-streep, het maalteken, de pijl, het
// beletselteken en de gekrulde aanhalingstekens). test/test-typografie.mjs
// bewaakt zowel die insluiting als het feit dat elk teken dat in handschrift
// op een bladzijde komt een glyph heeft.
//
// Draait in de browser (AL.fontHand) en in Node (module.exports).

